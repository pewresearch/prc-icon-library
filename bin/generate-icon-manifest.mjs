#!/usr/bin/env node
/**
 * src/icons/prc/*.svg → includes/icon-manifest.php + build/icons/prc.svg
 * src/icons/brands/*.svg → includes/brands-manifest.php + build/icons/brands.svg
 *
 * Do not hand-register icons. PHP reads these lists and registers every
 * curated name as `prc/{name}` and every baked approved brand as
 * `brands/{name}` when the WordPress Icon API exists. The fill sprites are
 * the JS `@prc/icons` sheets for those collections. Missing names fail
 * closed — there is no Font Awesome Pro sprite fallback.
 *
 * Usage:
 *   node bin/generate-icon-manifest.mjs
 *   node bin/generate-icon-manifest.mjs --check
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
	BRAND_ICON_CATALOG,
	BRAND_ICON_NAMES,
	FILL_ICON_CATALOG,
	resolveApprovedBrands,
} from './fill-icon-catalog.mjs';
import {
	BRANDS_SVG_DIR_REL,
	CUSTOM_ICON_NAMES,
	FIRST_PASS_ICON_NAMES,
	SVG_DIR_REL,
	collectContractErrors,
	labelFromName,
} from './svg-contract.mjs';

const PLUGIN_ROOT = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	'..'
);
const SVG_DIR = path.join(PLUGIN_ROOT, SVG_DIR_REL);
const MANIFEST_REL = 'includes/icon-manifest.php';
const MANIFEST_PATH = path.join(PLUGIN_ROOT, MANIFEST_REL);
const BRANDS_MANIFEST_REL = 'includes/brands-manifest.php';
const BRANDS_MANIFEST_PATH = path.join(PLUGIN_ROOT, BRANDS_MANIFEST_REL);
const SKIPPED_BRANDS_REL = 'includes/skipped-brands.json';
const SKIPPED_BRANDS_PATH = path.join(PLUGIN_ROOT, SKIPPED_BRANDS_REL);
const BRANDS_SVG_DIR = path.join(PLUGIN_ROOT, BRANDS_SVG_DIR_REL);
const BRANDS_REL = 'includes/approved-brands.json';
const BRANDS_PATH = path.join(PLUGIN_ROOT, BRANDS_REL);
const CURATED_JSON_REL =
	'../prc-scripts/includes/scripts/src/@prc/icons/src/curated-prc-icons.json';
const CURATED_JSON_PATH = path.join(PLUGIN_ROOT, CURATED_JSON_REL);
const PRC_SPRITE_REL = 'build/icons/prc.svg';
const PRC_SPRITE_PATH = path.join(PLUGIN_ROOT, PRC_SPRITE_REL);
const BRANDS_SPRITE_REL = 'build/icons/brands.svg';
const BRANDS_SPRITE_PATH = path.join(PLUGIN_ROOT, BRANDS_SPRITE_REL);

function parseArgs(argv) {
	return { check: argv.includes('--check') };
}

function loadApprovedBrands() {
	const raw = JSON.parse(fs.readFileSync(BRANDS_PATH, 'utf8'));
	if (!Array.isArray(raw) || raw.some((name) => typeof name !== 'string')) {
		throw new Error(`${BRANDS_REL} must be a JSON array of strings`);
	}
	return raw;
}

function buildCuratedPickerJson() {
	return `${JSON.stringify(
		{
			prc: [...FIRST_PASS_ICON_NAMES],
			brands: loadApprovedBrands(),
		},
		null,
		'\t'
	)}\n`;
}

function phpSingleQuote(value) {
	return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function buildManifestPhp() {
	const names = fs
		.readdirSync(SVG_DIR)
		.filter((file) => file.endsWith('.svg'))
		.map((file) => file.slice(0, -4))
		.sort();

	const expected = [...FIRST_PASS_ICON_NAMES].sort();
	if (names.join('\0') !== expected.join('\0')) {
		const missing = expected.filter((n) => !names.includes(n));
		const extra = names.filter((n) => !expected.includes(n));
		throw new Error(
			[
				missing.length ? `Missing SVGs: ${missing.join(', ')}` : '',
				extra.length ? `Unexpected SVGs: ${extra.join(', ')}` : '',
			]
				.filter(Boolean)
				.join('\n')
		);
	}

	const entries = [];
	for (const name of FIRST_PASS_ICON_NAMES) {
		const svgPath = path.join(SVG_DIR, `${name}.svg`);
		const svg = fs.readFileSync(svgPath, 'utf8');
		const errors = collectContractErrors(svg, name);
		if (errors.length > 0) {
			throw new Error(errors.join('\n'));
		}
		const label =
			FILL_ICON_CATALOG[name]?.label ||
			(CUSTOM_ICON_NAMES.includes(name) ? labelFromName(name) : null);
		if (!label) {
			throw new Error(`No label for ${name}`);
		}
		entries.push({
			name,
			label,
			filePath: `${SVG_DIR_REL}/${name}.svg`,
		});
	}

	const body = phpEntriesBody(entries);

	return `<?php
/**
 * Generated PRC fill-icon registration list. Do not edit by hand.
 *
 * Regenerated by: node plugins/prc-icon-library/bin/generate-icon-manifest.mjs
 *
 * @package PRC_Icon_Library
 */

// phpcs:ignoreFile -- generated from src/icons/prc/*.svg

declare(strict_types=1);

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Curated fill icons. Keys are kebab-case icon names.
 *
 * @return array<string, array{label: string, file_path: string}>
 */
return array(
${body}
);
`;
}

function phpEntriesBody(entries) {
	return entries
		.map((entry) => {
			return `\t${phpSingleQuote(entry.name)} => array(\n\t\t'label'     => ${phpSingleQuote(entry.label)},\n\t\t'file_path' => ${phpSingleQuote(entry.filePath)},\n\t),`;
		})
		.join('\n');
}

function buildBrandsManifestPhp() {
	const names = fs.existsSync(BRANDS_SVG_DIR)
		? fs
				.readdirSync(BRANDS_SVG_DIR)
				.filter((file) => file.endsWith('.svg'))
				.map((file) => file.slice(0, -4))
				.sort()
		: [];

	const expected = [...BRAND_ICON_NAMES].sort();
	if (names.join('\0') !== expected.join('\0')) {
		const missing = expected.filter((n) => !names.includes(n));
		const extra = names.filter((n) => !expected.includes(n));
		throw new Error(
			[
				missing.length
					? `Missing brand SVGs: ${missing.join(', ')}`
					: '',
				extra.length
					? `Unexpected brand SVGs: ${extra.join(', ')}`
					: '',
			]
				.filter(Boolean)
				.join('\n')
		);
	}

	const entries = [];
	for (const name of BRAND_ICON_NAMES) {
		const svgPath = path.join(BRANDS_SVG_DIR, `${name}.svg`);
		const svg = fs.readFileSync(svgPath, 'utf8');
		const errors = collectContractErrors(svg, name);
		if (errors.length > 0) {
			throw new Error(errors.join('\n'));
		}
		const label = BRAND_ICON_CATALOG[name]?.label || labelFromName(name);
		entries.push({
			name,
			label,
			filePath: `${BRANDS_SVG_DIR_REL}/${name}.svg`,
		});
	}

	const body = phpEntriesBody(entries);

	return `<?php
/**
 * Generated approved-brand fill-icon registration list. Do not edit by hand.
 *
 * Regenerated by: node plugins/prc-icon-library/bin/generate-icon-manifest.mjs
 *
 * @package PRC_Icon_Library
 */

// phpcs:ignoreFile -- generated from src/icons/brands/*.svg

declare(strict_types=1);

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Approved brand fill icons. Keys are kebab-case icon names.
 *
 * @return array<string, array{label: string, file_path: string}>
 */
return array(
${body}
);
`;
}

function buildSkippedBrandsJson() {
	const { skipped } = resolveApprovedBrands();
	return `${JSON.stringify(skipped, null, '\t')}\n`;
}

/**
 * Combine fill SVGs into a sprite sheet (`build/icons/{prc|brands}.svg`).
 *
 * @param {string}   svgDir Directory of contract-valid fill SVGs.
 * @param {string[]} names  Symbol ids in sheet order.
 * @return {string} Sprite markup.
 */
function buildFillSprite(svgDir, names) {
	const symbols = names.map((name) => {
		const svg = fs.readFileSync(path.join(svgDir, `${name}.svg`), 'utf8');
		const inner = svg
			.replace(/^<svg[^>]*>\s*/, '')
			.replace(/\s*<\/svg>\s*$/, '')
			.trim();
		const indented = inner.replace(/\n\t/g, '\n\t\t');
		return `\t<symbol id="${name}" viewBox="0 0 24 24">\n\t\t${indented}\n\t</symbol>`;
	});
	return `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`;
}

function buildPrcSprite() {
	return buildFillSprite(SVG_DIR, FIRST_PASS_ICON_NAMES);
}

function buildBrandsSprite() {
	return buildFillSprite(BRANDS_SVG_DIR, BRAND_ICON_NAMES);
}

function assertFileMatches(filePath, expected, rel, command) {
	if (!fs.existsSync(filePath)) {
		throw new Error(`Missing ${rel}. Run ${command}.`);
	}
	const current = fs.readFileSync(filePath, 'utf8').replace(/\r\n/g, '\n');
	if (current !== expected) {
		throw new Error(`${rel} is stale. Run: ${command}`);
	}
}

function main(argv = process.argv.slice(2)) {
	const { check } = parseArgs(argv);
	const php = buildManifestPhp();
	const brandsPhp = buildBrandsManifestPhp();
	const skippedBrands = buildSkippedBrandsJson();
	const curatedJson = buildCuratedPickerJson();
	const sprite = buildPrcSprite();
	const brandsSprite = buildBrandsSprite();
	const command = 'npm run generate:icon-manifest -w @prc/icon-library';

	if (check) {
		assertFileMatches(MANIFEST_PATH, php, MANIFEST_REL, command);
		assertFileMatches(
			BRANDS_MANIFEST_PATH,
			brandsPhp,
			BRANDS_MANIFEST_REL,
			command
		);
		assertFileMatches(
			SKIPPED_BRANDS_PATH,
			skippedBrands,
			SKIPPED_BRANDS_REL,
			command
		);
		assertFileMatches(
			CURATED_JSON_PATH,
			curatedJson,
			CURATED_JSON_REL,
			command
		);
		assertFileMatches(PRC_SPRITE_PATH, sprite, PRC_SPRITE_REL, command);
		assertFileMatches(
			BRANDS_SPRITE_PATH,
			brandsSprite,
			BRANDS_SPRITE_REL,
			command
		);
		process.stdout.write(
			`OK ${MANIFEST_REL}, ${BRANDS_MANIFEST_REL}, curated picker JSON, ${PRC_SPRITE_REL}, and ${BRANDS_SPRITE_REL} match fill SVGs\n`
		);
		return;
	}

	fs.mkdirSync(path.dirname(MANIFEST_PATH), { recursive: true });
	fs.writeFileSync(MANIFEST_PATH, php);
	fs.writeFileSync(BRANDS_MANIFEST_PATH, brandsPhp);
	fs.writeFileSync(SKIPPED_BRANDS_PATH, skippedBrands);
	fs.mkdirSync(path.dirname(CURATED_JSON_PATH), { recursive: true });
	fs.writeFileSync(CURATED_JSON_PATH, curatedJson);
	fs.mkdirSync(path.dirname(PRC_SPRITE_PATH), { recursive: true });
	fs.writeFileSync(PRC_SPRITE_PATH, sprite);
	fs.mkdirSync(path.dirname(BRANDS_SPRITE_PATH), { recursive: true });
	fs.writeFileSync(BRANDS_SPRITE_PATH, brandsSprite);
	process.stdout.write(`Wrote ${MANIFEST_REL}\n`);
	process.stdout.write(`Wrote ${BRANDS_MANIFEST_REL}\n`);
	process.stdout.write(`Wrote ${SKIPPED_BRANDS_REL}\n`);
	process.stdout.write(`Wrote ${CURATED_JSON_REL}\n`);
	process.stdout.write(`Wrote ${PRC_SPRITE_REL}\n`);
	process.stdout.write(`Wrote ${BRANDS_SPRITE_REL}\n`);
}

try {
	main();
} catch (error) {
	process.stderr.write(`${error instanceof Error ? error.message : error}\n`);
	process.exitCode = 1;
}
