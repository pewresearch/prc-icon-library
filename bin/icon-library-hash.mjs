/**
 * Content hash of the registered fill SVGs. prc-scripts keys the icon
 * object caches on it, so caches cold-start only when an SVG is added,
 * removed, or changed, not on every platform version bump.
 */

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

import { BRAND_ICON_NAMES } from './fill-icon-catalog.mjs';
import {
	BRANDS_SVG_DIR_REL,
	FIRST_PASS_ICON_NAMES,
	SVG_DIR_REL,
} from './svg-contract.mjs';

export const ICON_LIBRARY_HASH_REL = 'includes/icon-library-hash.php';
export const ICON_LIBRARY_HASH_LENGTH = 16;

/** @typedef {{ collection: string, name: string, svg: string }} IconLibraryEntry */

/**
 * Hash icon entries. Order does not matter; line endings are normalized.
 *
 * @param {IconLibraryEntry[]} entries Registered icons.
 * @return {string} Lowercase hex, ICON_LIBRARY_HASH_LENGTH characters.
 */
export function computeIconLibraryHash(entries) {
	const hash = crypto.createHash('sha256');
	const sorted = [...entries].sort((a, b) => {
		const left = `${a.collection}/${a.name}`;
		const right = `${b.collection}/${b.name}`;
		if (left === right) {
			return 0;
		}
		return left < right ? -1 : 1;
	});
	for (const entry of sorted) {
		hash.update(`${entry.collection}/${entry.name}\0`);
		hash.update(entry.svg.replace(/\r\n/g, '\n'));
		hash.update('\0');
	}
	return hash.digest('hex').slice(0, ICON_LIBRARY_HASH_LENGTH);
}

/**
 * Read every registered `prc/*` and `brands/*` fill SVG from disk.
 *
 * @param {string} pluginRoot Absolute path to plugins/prc-icon-library.
 * @return {IconLibraryEntry[]} Entries for computeIconLibraryHash().
 */
export function collectIconLibraryEntries(pluginRoot) {
	const read = (dirRel, name) =>
		fs.readFileSync(path.join(pluginRoot, dirRel, `${name}.svg`), 'utf8');
	return [
		...FIRST_PASS_ICON_NAMES.map((name) => ({
			collection: 'prc',
			name,
			svg: read(SVG_DIR_REL, name),
		})),
		...BRAND_ICON_NAMES.map((name) => ({
			collection: 'brands',
			name,
			svg: read(BRANDS_SVG_DIR_REL, name),
		})),
	];
}

/**
 * Generated PHP file that returns the hash.
 *
 * @param {string} hash Value from computeIconLibraryHash().
 * @return {string} PHP source.
 */
export function buildIconLibraryHashPhp(hash) {
	if (!new RegExp(`^[a-f0-9]{${ICON_LIBRARY_HASH_LENGTH}}$`).test(hash)) {
		throw new Error(`Invalid icon library hash: ${hash}`);
	}
	return `<?php
/**
 * Generated icon library content hash. Do not edit by hand.
 *
 * Regenerated by: node plugins/prc-icon-library/bin/generate-icon-manifest.mjs
 *
 * @package PRC_Icon_Library
 */

// phpcs:ignoreFile -- generated from src/icons/{prc,brands}/*.svg

declare(strict_types=1);

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

return '${hash}';
`;
}
